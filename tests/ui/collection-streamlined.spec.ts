test('Alola appearance and Mega or Tera battle controls use persistent game state', async ({ page }) => {
  test.setTimeout(90_000);
  await page.routeWebSocket('**', socket => socket.close());
  await page.route('**/api/auth/me', route => route.fulfill({ json: { user: null } }));
  await page.route('**/api/connectome', route => route.fulfill({ json: { available: false } }));
  await page.route(/\.(?:glb|gltf)(?:\?.*)?$/, route => route.abort());
  const game = createGame(4, 'forms-ui'), charizard = createMonster(game, 6, 50), raichu = createMonster(game, 26, 30), enemy = createMonster(game, 7, 50);
  game.player.team = [charizard]; game.player.box = [raichu];
  const load = async () => {
    await page.locator('#import-file').setInputFiles({ name: 'forms.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(packSave(game, graph, { ...defaultView(), openWorldPaused: true }))) });
    await expect(page.locator('#toast')).toContainText('불러왔습니다');
  };
  await page.goto('/'); await page.locator('[data-starter="152"]').click(); await load();
  await page.locator('[data-tab="team"]').click();
  await page.locator(`[data-monster="${raichu.instanceId}"]`).click();
  await page.locator('#monster-form').selectOption('alola');
  await expect(page.locator('.detail-title .type-psychic')).toBeVisible();
  await expect(page.locator('.detail-portrait img')).toHaveAttribute('src', /10100\.png$/);
  await page.locator('#box-search').fill('알로라 에스퍼');
  await expect(page.locator('.box-monster')).toHaveCount(1);
  game.battle = { kind: 'wild', regionId: game.regionId, player: { team: game.player.team, activeIndex: 0 }, enemy: { team: [enemy], activeIndex: 0 }, turn: 1, canRun: true };
  await load(); await page.locator('[data-tab="map"]').click();
  await page.locator('[data-mega-form]').selectOption('charizard-mega-x');
  await page.locator('[data-battle-transformation="mega"]').click();
  await expect(page.locator('[data-transformation-active="mega"]')).toBeVisible();
  await expect(page.locator('.player.combatant .type-dragon')).toBeVisible();
  await expect(page.locator('.player.combatant img')).toHaveAttribute('src', /10034\.png$/);
  await load();
  await page.locator('[data-tera-type]').selectOption('water');
  await page.locator('[data-battle-transformation="tera"]').click();
  await expect(page.locator('[data-transformation-active="tera"]')).toHaveText('물 테라스탈');
  await expect(page.locator('.player.combatant .type-water')).toBeVisible();
  await page.locator('#save-now').click();
  await expect(page.locator('#save-state')).toContainText('저장됨');
  await page.reload();
  await expect(page.locator('[data-transformation-active="tera"]')).toHaveText('물 테라스탈');
});
